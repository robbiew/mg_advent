package main

import (
	"encoding/binary"
	"fmt"
	"strings"
	"time"

	"github.com/robbiew/advent/internal/art"
)

// Placeholder screens are CP437 ANSI drawn inside 79 columns, so nothing
// ever reaches column 80 (which would autowrap), with a SAUCE record like
// real art.
const (
	cols     = 79 // visible width of every line
	inner    = cols - 2
	rows     = 25 // framed screens fill an 80x25 terminal
	tallRows = 45 // Info/Members are taller than the screen, to exercise scrolling
)

// CP437 glyphs (the source stays ASCII; these are the raw bytes).
const (
	boxTL, boxTR, boxBL, boxBR = "\xc9", "\xbb", "\xc8", "\xbc"
	boxH, boxV                 = "\xcd", "\xba"
	block, shade, halfUp       = "\xdb", "\xb2", "\xdf"
	halfDown                   = "\xdc"
	laquo, raquo               = "\xae", "\xaf"
)

func sgr(codes string) string { return "\x1b[" + codes + "m" }

var (
	reset   = sgr("0")
	border  = sgr("0;1;32") // bright green
	red     = sgr("0;1;31")
	yellow  = sgr("0;1;33")
	white   = sgr("0;1;37")
	cyan    = sgr("0;36")
	grey    = sgr("0;1;30")
	menuKey = sgr("0;1;37;41") // white on red
)

// line is one row of a framed screen: plain CP437 text (no escapes, so its
// byte length is its width) drawn centred in one colour.
type line struct {
	text  string
	color string
}

// screen describes one placeholder file.
type screen struct {
	file  string // file name inside the year directory
	title string // what the screen is, e.g. "Welcome screen"
	day   int    // 1-25 for a daily door, else 0
	tall  bool   // Info/Members: a scrolling text screen, not a frame
}

// screensFor lists every file a year's pack needs.
func screensFor(year int) []screen {
	list := []screen{
		{file: "WELCOME.ANS", title: "Welcome screen and year menu"},
		{file: "COMEBACK.ANS", title: "Come back tomorrow screen"},
		{file: "GOODBYE.ANS", title: "Goodbye screen"},
		{file: "INFOFILE.ANS", title: "Info file", tall: true},
		{file: "MEMBERS.ANS", title: "Member list", tall: true},
	}
	for day := 1; day <= 25; day++ {
		list = append(list, screen{file: art.DayFileNames(year, day)[0], title: fmt.Sprintf("Door %d", day), day: day})
	}
	return list
}

// render returns the placeholder file for s. earlier lists the installed
// years before this one, oldest first; their menu keys are 1, 2, 3...
func render(s screen, year int, earlier []int, date time.Time) []byte {
	var body []string
	if s.tall {
		body = tallScreen(s, year)
	} else {
		body = framedScreen(s, year, earlier)
	}
	content := reset + strings.Join(body, "\r\n") + reset
	height := len(body)
	return append([]byte(content), sauceRecord(s, year, date, len(content), height)...)
}

func framedScreen(s screen, year int, earlier []int) []string {
	content := []line{
		{},
		{fmt.Sprintf("MiSTiGRiS ADVENT CALENDAR %d", year), yellow},
		{s.title, white},
		{},
		{strings.Repeat(halfDown, 31), red},
		{shade + shade + shade + "  P L A C E H O L D E R  " + shade + shade + shade, red},
		{strings.Repeat(halfUp, 31), red},
		{},
	}
	switch {
	case s.day > 0:
		for _, row := range bigNumber(s.day) {
			content = append(content, line{row, yellow})
		}
		content = append(content,
			line{},
			line{fmt.Sprintf("December %d, %d  -  door %d of 25", s.day, year, s.day), white},
			line{laquo + " previous door        Q back        next door " + raquo, cyan},
		)
	case s.file == "WELCOME.ANS" || s.file == "COMEBACK.ANS":
		if s.file == "COMEBACK.ANS" {
			content = append(content, line{"COME BACK TOMORROW!", yellow},
				line{"The next door opens at midnight.", white}, line{})
		}
		content = append(content, menuLines(year, earlier)...)
	case s.file == "GOODBYE.ANS":
		content = append(content, line{"See you again soon, and happy holidays!", yellow})
	}

	// The last two rows say what to replace this file with.
	for len(content) < rows-4 {
		content = append(content, line{})
	}
	content = append(content,
		line{fmt.Sprintf("Drop the real art in as art/%d/%s", year, s.file), cyan},
		line{art.PlaceholderMarker + "  -  generated by tools/mkplaceholders", grey},
	)

	out := []string{border + boxTL + strings.Repeat(boxH, inner) + boxTR}
	for _, l := range content[:rows-2] {
		out = append(out, border+boxV+l.color+centre(l.text, inner)+border+boxV)
	}
	return append(out, border+boxBL+strings.Repeat(boxH, inner)+boxBR)
}

// menuLines lists the keys the door accepts on the welcome/comeback screens.
func menuLines(year int, earlier []int) []line {
	out := []line{{fmt.Sprintf("NAVIGATE  %s %s  or ENTER   browse the %d calendar", laquo, raquo, year), white}}
	var keys []string
	for i, y := range earlier {
		keys = append(keys, fmt.Sprintf("%d  %d ADVENT", i+1, y))
	}
	for i := 0; i < len(keys); i += 3 {
		out = append(out, line{strings.Join(keys[i:min(i+3, len(keys))], "     "), cyan})
	}
	return append(out,
		line{"[ ]  or  PGUP PGDN   previous / next year", cyan},
		line{"I  INFO   M  MEMBERS   A  CREDITS   S  SLIDESHOW", cyan},
		line{"?  HELP      Q  QUIT", cyan})
}

func tallScreen(s screen, year int) []string {
	out := []string{
		yellow + fmt.Sprintf("MiSTiGRiS ADVENT CALENDAR %d - %s", year, s.title),
		red + shade + shade + shade + "  P L A C E H O L D E R  " + shade + shade + shade,
		cyan + fmt.Sprintf("Drop the real art in as art/%d/%s", year, s.file),
		grey + art.PlaceholderMarker + "  -  generated by tools/mkplaceholders",
		"",
	}
	for n := len(out) + 1; n <= tallRows; n++ {
		text := fmt.Sprintf("Line %02d of %d - placeholder %s text. Scroll with the arrow keys.", n, tallRows, strings.ToLower(s.title))
		if s.file == "MEMBERS.ANS" {
			text = fmt.Sprintf("Member %02d %s artist handle  /  group  /  contribution", n-5, strings.Repeat(".", 20))
		}
		out = append(out, white+text)
	}
	return out
}

// bigNumber draws n in 5-row block digits.
func bigNumber(n int) []string {
	font := [10][5]string{
		{"#####", "#   #", "#   #", "#   #", "#####"},
		{"  #  ", " ##  ", "  #  ", "  #  ", " ### "},
		{"#####", "    #", "#####", "#    ", "#####"},
		{"#####", "    #", " ####", "    #", "#####"},
		{"#   #", "#   #", "#####", "    #", "    #"},
		{"#####", "#    ", "#####", "    #", "#####"},
		{"#####", "#    ", "#####", "#   #", "#####"},
		{"#####", "    #", "   # ", "  #  ", "  #  "},
		{"#####", "#   #", "#####", "#   #", "#####"},
		{"#####", "#   #", "#####", "    #", "#####"},
	}
	// Each font cell is drawn two columns wide, so blanks double too.
	wide := strings.NewReplacer("#", block+block, " ", "  ")
	digits := fmt.Sprint(n)
	out := make([]string, 5)
	for r := range out {
		var parts []string
		for _, d := range digits {
			parts = append(parts, wide.Replace(font[d-'0'][r]))
		}
		out[r] = strings.Join(parts, "  ")
	}
	return out
}

func centre(s string, width int) string {
	pad := max(width-len(s), 0)
	return strings.Repeat(" ", pad/2) + s + strings.Repeat(" ", pad-pad/2)
}

// sauceRecord returns the EOF marker and the 128-byte SAUCE trailer
// (http://www.acid.org/info/sauce/sauce.htm) describing an 80-column ANSi.
func sauceRecord(s screen, year int, date time.Time, size, height int) []byte {
	rec := make([]byte, 128)
	put := func(off, width int, v string) {
		copy(rec[off:off+width], (v + strings.Repeat(" ", width))[:width])
	}
	put(0, 7, "SAUCE00")
	put(7, 35, fmt.Sprintf("%d placeholder: %s", year, s.file))
	put(42, 20, art.PlaceholderMarker)
	put(62, 20, "MiSTiGRiS")
	put(82, 8, date.Format("20060102"))
	binary.LittleEndian.PutUint32(rec[90:], uint32(size))
	rec[94], rec[95] = 1, 1 // character data, ANSi
	binary.LittleEndian.PutUint16(rec[96:], 80)
	binary.LittleEndian.PutUint16(rec[98:], uint16(height))
	// rec[104] comment count, rec[105] flags: zero. TInfoS names the font.
	copy(rec[106:], "IBM VGA")
	return append([]byte{0x1a}, rec...)
}
